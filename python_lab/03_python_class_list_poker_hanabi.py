class Carta:
  def __init__(self, numero, palo):
      self.numero = numero
      self.palo = palo

  def __repr__(self):
      return f"{self.numero} de {self.palo}"

  #Mejoras de la clase barajas
class Baraja:
  def __init__(self, numeros, palos):
      self.cartas = []
      for palo in palos:
          for numero in numeros:
              self.cartas.append(Carta(numero, palo))

  def shuffle(self):
      print("Barajando las cartas")
      random.shuffle(self.cartas)

  def draw(self):
      if len(self.cartas) > 0:
          return self.cartas.pop()

      else:
        return "No quedan cartas"


class HandHanabi:
  def __init__(self, nombre):
      self.nombre = nombre
      self.cartas = [] #inicializamos con la mano vacía

#REcibimos cartas
  def add_card(self, carta):
      self.cartas.append(carta)

#descartamos cartas
  def discard_card(self, posicion):
    #verificamos que la posición sea válida (que no se pase del rango)
      if 0 <= posicion < len(self.cartas):
          carta_tirada = self.cartas.pop(posicion)
          print(f"{self.nombre} ha descartado: {carta_tirada}")
          return carta_tirada
      else:
          print("Error: {self.nombre} esa posición no existe en tu mano")
          return None

