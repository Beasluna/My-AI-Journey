import random

#Baraja de texto
class Baraja:
  def __init__(self, numeros, palos):
      self.numeros = numeros
      self.palos = palos
      self.cartas = []

      for palo in self.palos:
          for numero in self.numeros:
              carta_nueva = f"{numero} de {palo}"
              self.cartas.append(carta_nueva)

  def shuffle(self):
      print("Barajar el mazo")
      random.shuffle(self.cartas)

  def draw(self):
      if len(self.cartas) > 0:
          return self.cartas.pop()
      else:
          return "No quedan cartas"
